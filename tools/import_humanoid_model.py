"""Export the reviewed humanoid_model physics into portable repository assets.

Run once with the upstream archive available. The application itself never
imports upstream Python code or depends on the archive's original location.
The upstream modules are executed only by this explicit developer command;
review an unfamiliar archive before importing it.
"""

from __future__ import annotations

import argparse
from dataclasses import fields, is_dataclass
from enum import Enum
import hashlib
import importlib
import json
from pathlib import Path
import shutil
import sys
from types import ModuleType
from xml.etree import ElementTree as ET

import mujoco
import numpy as np


REPOSITORY = Path(__file__).resolve().parents[1]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def serializable(value):
    """Preserve the upstream typed passport without numpy/pickle objects."""
    if is_dataclass(value):
        return {field.name: serializable(getattr(value, field.name))
                for field in fields(value)}
    if isinstance(value, Enum):
        return value.value
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, dict):
        return {str(key): serializable(item) for key, item in value.items()}
    if isinstance(value, (tuple, list)):
        return [serializable(item) for item in value]
    if isinstance(value, Path):
        raise ValueError("Absolute filesystem paths do not belong in the export")
    return value


def export(source: Path, destination: Path) -> dict:
    source = source.resolve()
    destination = destination.resolve()
    clean_root = source / "refactor" / "clean"
    source_root = clean_root / "src"
    if not (source_root / "physical_model" / "humanoid.py").is_file():
        raise FileNotFoundError("Expected humanoid_model/refactor/clean/src")
    if source == destination or source in destination.parents:
        raise ValueError("Export must not modify the upstream archive")

    # Avoid mujoco_runtime.__init__: it eagerly imports planners/viewers which
    # are unrelated to this physics-only export. Relative builder imports work
    # normally through this package shell; physical_model is engine-neutral.
    sys.path.insert(0, str(source_root))
    runtime = ModuleType("mujoco_runtime")
    runtime.__path__ = [str(source_root / "mujoco_runtime")]
    sys.modules["mujoco_runtime"] = runtime
    physical = importlib.import_module("physical_model")
    builder = importlib.import_module("mujoco_runtime.model_builder")
    numerics_module = importlib.import_module("mujoco_runtime.numerics")
    reference = importlib.import_module("mujoco_runtime.reference_actuator")
    cad_module = importlib.import_module("mujoco_runtime.cad_visual")
    passport = physical.humanoid_passport()
    surface = physical.painted_steel_on_smooth_wood_v0()
    numerics = numerics_module.passive_research_numerics_v0()
    actuator = reference.legacy_mujoco_position_reference_v0(passport.joint_names)
    cad = cad_module.bundled_humanoid_cad_visual_profile()
    bundle = builder.build_actuated_humanoid_model(
        passport, surface, numerics, actuator, cad_visual=cad,
    )

    # Validation happens before copying any assets. These values are explicit
    # properties of the reviewed model, not measurements of the real robot.
    if not np.isclose(bundle.model.body_mass.sum(), 3.0942, atol=1e-10):
        raise ValueError("Unexpected upstream mass; review the new passport")
    if bundle.model.nu != 20 or bundle.model.nbody != 22:
        raise ValueError("Expected 20 drives and 21 robot bodies")
    if np.max(np.abs(bundle.model.actuator_forcerange)) > 1.5:
        raise ValueError("Unexpected upstream reference torque limit")
    mesh_bytes = cad.load_asset_bytes()  # validates all original SHA-256 values

    destination.mkdir(parents=True, exist_ok=True)
    asset_dir = destination / "meshes"
    asset_dir.mkdir(exist_ok=True)
    for asset in cad.assets:
        # The upstream loader has already required a plain filename.
        shutil.copyfile(cad.asset_root / asset.file_name, asset_dir / asset.file_name)
    shutil.copyfile(cad.asset_root / "manifest.json", asset_dir / "manifest.json")

    root = ET.fromstring(bundle.xml)
    root.find("compiler").set("meshdir", "meshes")
    root.insert(0, ET.Comment(
        " Generated by tools/import_humanoid_model.py. "
        "Source coordinates and joints are preserved; do not use as a "
        "hardware-calibrated drive model. "
    ))
    ET.indent(root, space="  ")
    xml = ET.tostring(root, encoding="unicode") + "\n"
    (destination / "source_scene.xml").write_text(xml, encoding="utf-8")
    loaded = mujoco.MjModel.from_xml_path(str(destination / "source_scene.xml"))
    if not np.allclose(loaded.body_mass, bundle.model.body_mass):
        raise AssertionError("Portable asset export changed the body masses")

    snapshot = {
        "schema_version": 1,
        "passport": serializable(passport),
        "surface": serializable(surface),
        "numerics": serializable(numerics),
        "actuator_reference": serializable(actuator),
        "scene_geometry": serializable(physical.humanoid_scene_geometry_profile(passport)),
        "joint_order": list(bundle.joint_names),
        "body_order": list(bundle.body_names),
        "visual_mapping_status": bundle.visual_mapping_status,
    }
    (destination / "physical_snapshot.json").write_text(
        json.dumps(snapshot, ensure_ascii=False, indent=2, allow_nan=False) + "\n",
        encoding="utf-8",
    )
    source_files = {}
    for package in (source_root / "physical_model", source_root / "mujoco_runtime"):
        for path in sorted(package.glob("*.py")):
            # Record precisely the modules loaded by the exporter, not unrelated
            # trajectory planners that are not included in the physical model.
            module_name = f"{package.name}.{path.stem}"
            if module_name in sys.modules or path.name == "__init__.py" and package.name == "physical_model":
                source_files[path.relative_to(source).as_posix()] = sha256(path)
    result = {
        "schema_version": 1,
        "source_project": "humanoid_model",
        "source_files_sha256": source_files,
        "cad_manifest_sha256": sha256(asset_dir / "manifest.json"),
        "source_scene_sha256": sha256(destination / "source_scene.xml"),
        "snapshot_sha256": sha256(destination / "physical_snapshot.json"),
        "dynamic_mass_kg": float(loaded.body_mass.sum()),
        "robot_bodies": loaded.nbody - 1,
        "actuators": loaded.nu,
        "mesh_count": len(mesh_bytes),
        "cad_mass_and_com": "Upstream provenance claims; original drawing not included",
        "inertia": "Finite rod/box approximations, not CAD inertia tensors",
        "actuators_status": "Numerical reference; not identified AR-S430-01 dynamics",
        "self_collision": False,
    }
    (destination / "import_provenance.json").write_text(
        json.dumps(result, ensure_ascii=False, indent=2, allow_nan=False) + "\n",
        encoding="utf-8",
    )
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True,
                        help="Root of the reviewed humanoid_model archive")
    parser.add_argument("--destination", type=Path,
                        default=REPOSITORY / "models" / "volodka")
    args = parser.parse_args()
    sys.dont_write_bytecode = True
    print(json.dumps(export(args.source, args.destination), ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
